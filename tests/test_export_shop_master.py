def csv_columns(file_name):
    return (SHOP_MASTER / file_name).read_text(encoding="utf-8").splitlines()[0]


def load_shuffled(conn, table, file_name):
    # The committed rows in a shuffled order, so only ORDER BY id::bigint (not the load
    # order, and not text order: '10' < '4') can give the committed file back.
    lines = (SHOP_MASTER / file_name).read_text(encoding="utf-8").splitlines(keepends=True)
    header, rows = lines[0], lines[1:]
    random.Random(20261119).shuffle(rows)
    query = sql.SQL("COPY {} ({}) FROM STDIN WITH (FORMAT csv, HEADER)").format(
        sql.Identifier("warehouse", table), sql.SQL(header.strip())
    )
    with conn.cursor().copy(query) as copy:
        copy.write(header + "".join(rows))


