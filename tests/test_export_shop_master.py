@pytest.fixture
def warehouse(test_db):
    # A fresh P2-shaped warehouse per test: the committed export plus P2's extra rows.
    with psycopg.connect(test_db, autocommit=True) as conn:
        conn.execute("DROP SCHEMA IF EXISTS warehouse CASCADE")
        conn.execute("CREATE SCHEMA warehouse")
        conn.execute(CUSTOMER_TABLE)
        conn.execute(PRODUCT_TABLE)
        load_shuffled(conn, "dim_customer", "customers.csv")
        load_shuffled(conn, "dim_product", "products.csv")
        for statement in EXTRA_ROWS:
            conn.execute(statement)
    return test_db


def export_env(conninfo, target, **extra):
    # The script's own settings, from the test database's connection string. The
    # test role's real password goes in P2_EXPORT_PASSWORD; PASSWORD is only a marker
    # when the role needs none.
    params = conninfo_to_dict(conninfo)
    env = {key: value for key, value in os.environ.items() if not key.startswith("PG")}
    env.update(
        P2_EXPORT_HOST=params.get("host", "127.0.0.1"),
        P2_EXPORT_PORT=str(params.get("port", 5432)),
        P2_EXPORT_DB=params["dbname"],
        P2_EXPORT_USER=params["user"],
        P2_EXPORT_PASSWORD=params.get("password") or PASSWORD,
        SHOP_MASTER_DIR=str(target),
    )
    env.update(extra)
    return env


def run_export(env):
    return subprocess.run(
        [sys.executable, str(EXPORT_SCRIPT)],
        capture_output=True,
        text=True,
        timeout=120,
        env=env,
    )


def load_export_module():
    spec = importlib.util.spec_from_file_location("export_under_test", EXPORT_SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_export_equals_the_committed_csvs_byte_for_byte(warehouse, tmp_path):
    target = tmp_path / "shop_master_export"
    env = export_env(warehouse, target)

    result = run_export(env)

    assert result.returncode == 0, result.stderr
    for file_name in ("customers.csv", "products.csv"):
        assert (target / file_name).read_bytes() == (SHOP_MASTER / file_name).read_bytes()
    # Only the two files: the temporary files are gone.
    assert sorted(path.name for path in target.iterdir()) == ["customers.csv", "products.csv"]
    assert "customers.csv: 497 rows" in result.stdout
    assert "products.csv: 147 rows" in result.stdout
    # The password never reaches the output.
    password = env["P2_EXPORT_PASSWORD"]
    assert password not in result.stdout and password not in result.stderr


def test_session_is_read_only_with_a_statement_timeout(warehouse):
    export = load_export_module()
    params = conninfo_to_dict(warehouse)
    settings = export.ExportSettings(
        host=params.get("host", "127.0.0.1"),
        port=int(params.get("port", 5432)),
        dbname=params["dbname"],
        user=params["user"],
        password=params.get("password") or "",
    )

    with export.connect(settings) as conn:
        assert conn.execute("SHOW transaction_read_only").fetchone()[0] == "on"
        assert conn.execute("SHOW statement_timeout").fetchone()[0] == "2min"
        with pytest.raises(errors.ReadOnlySqlTransaction):
            conn.execute("DELETE FROM warehouse.dim_customer")
    with psycopg.connect(warehouse) as conn:
        [(rows,)] = conn.execute("SELECT count(*) FROM warehouse.dim_customer").fetchall()
    assert rows == 497 + 2 + 3


@pytest.mark.parametrize(
    ("change", "message"),
    [
        (
            "UPDATE warehouse.dim_customer SET age = NULL WHERE customer_id = '42'",
            "warehouse.dim_customer: 1 current row(s) with a NULL required column",
        ),
        (
            "INSERT INTO warehouse.dim_product (product_id, product_name, category, brand,"
            " product_status, original_price) VALUES ('P-9', 'X', 'Books', 'B', 'active', 1)",
            "warehouse.dim_product: 1 current row(s) whose product_id is not a positive integer",
        ),
        (
            "INSERT INTO warehouse.dim_customer (customer_id, customer_name, email, gender, age,"
            " membership_tier, loyalty_points, preferred_language, customer_segment,"
            " is_prime_user, home_city, home_state, country, signup_date)"
            " SELECT customer_id, customer_name, email, gender, age, membership_tier,"
            " loyalty_points, preferred_language, customer_segment, is_prime_user, home_city,"
            " home_state, country, signup_date FROM warehouse.dim_customer"
            " WHERE customer_id = '7' AND is_current",
            "warehouse.dim_customer: 498 current rows but 497 distinct customer_id",
        ),
    ],
    ids=["null_required_value", "non_numeric_id", "two_current_rows"],
)
def test_bad_rows_exit_2_and_leave_the_folder_unchanged(warehouse, tmp_path, change, message):
    with psycopg.connect(warehouse, autocommit=True) as conn:
        conn.execute(change)
    target = tmp_path / "shop_master_export"
    target.mkdir()
    (target / "customers.csv").write_text("earlier export\n", encoding="utf-8")

    result = run_export(export_env(warehouse, target))

    assert result.returncode == 2
    assert result.stderr.strip() == f"[export] error: {message}; nothing was written"
    assert sorted(path.name for path in target.iterdir()) == ["customers.csv"]
    assert (target / "customers.csv").read_text(encoding="utf-8") == "earlier export\n"


@pytest.mark.parametrize(
    ("env", "message"),
    [
        (
            {"SHOP_MASTER_DIR": str(SHOP_MASTER)},
            f"{SHOP_MASTER} is the committed reference data; export to another folder",
        ),
        (
            {"SHOP_MASTER_DIR": "reference-data/shop_master", "PROJECT1_ROOT": str(ROOT)},
            f"{SHOP_MASTER} is the committed reference data; export to another folder",
        ),
        ({"SHOP_MASTER_DIR": ""}, "SHOP_MASTER_DIR is not set"),
        ({"P2_EXPORT_PASSWORD": ""}, "P2_EXPORT_PASSWORD is not set"),
        ({"P2_EXPORT_PORT": "54x"}, "P2_EXPORT_PORT must be a port number, got '54x'"),
    ],
    ids=["committed_folder", "committed_folder_relative", "no_folder", "no_password", "bad_port"],
)
def test_refuses_bad_settings_before_connecting(tmp_path, env, message):
    # Port 1 on loopback: a connection attempt would fail with a different message.
    base = {
        **{key: value for key, value in os.environ.items() if not key.startswith("PG")},
        "P2_EXPORT_HOST": "127.0.0.1",
        "P2_EXPORT_PORT": "1",
        "P2_EXPORT_PASSWORD": PASSWORD,
        "SHOP_MASTER_DIR": str(tmp_path / "out"),
    }
    before = {path.name: path.read_bytes() for path in SHOP_MASTER.iterdir()}

    result = run_export({**base, **env})

    assert result.returncode == 2
    assert result.stderr.strip() == f"[export] error: {message}"
    assert PASSWORD not in result.stdout + result.stderr
    assert {path.name: path.read_bytes() for path in SHOP_MASTER.iterdir()} == before
    assert not (tmp_path / "out").exists()


def module_list_constant(path, name):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == name for target in node.targets
        ):
            return ast.literal_eval(node.value)
    raise AssertionError(f"{name} not found in {path}")


def test_export_columns_are_the_producers_and_the_committed_headers():
    producer = ROOT / "data-generator" / "producer.py"
    for name, file_name in (
        ("CUSTOMER_COLUMNS", "customers.csv"),
        ("PRODUCT_COLUMNS", "products.csv"),
    ):
        columns = module_list_constant(EXPORT_SCRIPT, name)
        assert columns == module_list_constant(producer, name)
        assert ",".join(columns) == csv_columns(file_name)


def test_export_folders_are_gitignored_but_the_committed_one_is_not():
    if shutil.which("git") is None or not (ROOT / ".git").exists():
        pytest.skip("git or the .git directory is not available")

    def ignored(path):
        result = subprocess.run(
            ["git", "check-ignore", "--no-index", "--quiet", path], cwd=ROOT, check=False
        )
        return result.returncode == 0

    assert ignored("reference-data/shop_master_export/customers.csv")
    assert ignored("reference-data/shop_master_2026-11-19/")
    assert not ignored("reference-data/shop_master/customers.csv")
